import { hashPassword, PBKDF2_ITERATIONS } from '../src/lib/auth/password.ts';

/**
 * Print the environment values for an operator login.
 *
 *   node scripts/hash-password.ts <username> <password>
 *
 * The password is read from argv and never written anywhere. What comes out is a PBKDF2 hash,
 * which is what goes into `.env.local` (gitignored) and into the Cloudflare secret. The
 * plaintext exists only in your shell history and in your head.
 *
 * A generated AUTH_SECRET comes with it: rotating that value invalidates every outstanding
 * session at once, which is the only revocation this design has.
 *
 * The hash is dot-separated rather than `$`-separated on purpose - see the note in
 * src/lib/auth/password.ts. `$` in an env value is expansion syntax, and it silently ate the
 * credential the first time this shipped.
 */

const [username, password] = process.argv.slice(2);

if (!username || !password) {
  console.error('usage: node scripts/hash-password.ts <username> <password>');
  process.exit(1);
}

if (password.length < 8) {
  console.error(`refusing: a ${password.length}-character password is not worth hashing.`);
  process.exit(1);
}

const hash = await hashPassword(password);
const secret = Buffer.from(crypto.getRandomValues(new Uint8Array(32))).toString('base64');

console.log(`# Generated by scripts/hash-password.ts - ${PBKDF2_ITERATIONS} PBKDF2 iterations.`);
console.log(`# Put these in .env.local (gitignored) and in your Cloudflare secrets.`);
console.log(`# The password itself appears nowhere in this output.`);
console.log(`ADMIN_USERNAME=${username}`);
console.log(`ADMIN_PASSWORD_HASH=${hash}`);
console.log(`AUTH_SECRET=${secret}`);
